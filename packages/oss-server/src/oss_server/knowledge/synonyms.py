"""Query-time synonyms from the active packs (ADR-0003, docs/search.md#synonyms).

Every taggable concept and individual of an active pack contributes one line of
equivalent labels to `synonyms_packs.txt` in the documents configset: its preferred
labels (all languages), alternative labels and hidden labels. The neutral text fields
expand a query word or phrase to the others at query time, so "Ulysses" finds texts
that say "Odysseus", and a hidden label (a known misspelling or OCR error) is found
when the correct form is searched.

The file is regenerated and the documents collection reloaded when a pack is imported
or activated (`api/knowledge.py`) and when the server starts (`entry.prepare`, after
the configsets are uploaded). Nothing is reindexed: synonyms apply only to queries.
"""

from __future__ import annotations

import logging
import re
import shutil
import tempfile
import unicodedata
from collections.abc import Iterable
from pathlib import Path
from typing import Any

log = logging.getLogger(__name__)

SYNONYMS_FILE = "synonyms_packs.txt"
# ZooKeeper refuses nodes over 1 MB by default; stay well below it
MAX_BYTES = 900_000
# A concept's other labels weigh this much against the words typed (thesaurus terms are
# related, not identical); an individual's names are equivalent (docs/search.md#synonyms)
CONCEPT_WEIGHT = 0.5
HEADER = (
    "# Query-time synonyms from the labels of the active packs: one line per concept, its\n"
    "# preferred, alternative and hidden labels. Generated by oss_server.knowledge.synonyms\n"
    "# on pack import and activation, and when the server starts; edits here are overwritten.\n"
)
# letters ASCII folding changes that NFKD does not decompose
_FOLD = str.maketrans(
    {
        "ß": "ss",
        "æ": "ae",
        "Æ": "AE",
        "œ": "oe",
        "Œ": "OE",
        "ø": "o",
        "Ø": "O",
        "đ": "d",
        "Đ": "D",
        "ł": "l",
        "Ł": "L",
        "þ": "th",
        "Þ": "TH",
        "ð": "d",
        "Ð": "D",
    }
)


def fold(label: str) -> str:
    """The label without accents: the form a query typed without them arrives in."""

    text = unicodedata.normalize("NFKD", label.translate(_FOLD))
    return "".join(ch for ch in text if not unicodedata.combining(ch))


def stopwords(languages: Iterable[str] | None = None, conf_dir: Path | None = None) -> set[str]:
    """The stop words of these languages (ISO codes; None: every language the documents
    configset has a list for), lower-cased."""

    if conf_dir is None:
        from oss_server.services import configset_dir

        conf_dir = configset_dir("documents")
    wanted = None if languages is None else {c for c in languages if c}
    words: set[str] = set()
    for path in sorted((conf_dir / "lang").glob("stopwords_*.txt")):
        if wanted is not None and path.stem.removeprefix("stopwords_") not in wanted:
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            word = line.split("|", 1)[0].strip()  # the snowball format comments with |
            if word and not word.startswith("#"):
                words.add(word.lower())
    return words


def usable(label: str, stop: set[str]) -> bool:
    """A label worth expanding: not a stop word, not a short acronym (a query is lowercased
    before the synonyms apply, so "US" would also expand "us"). Punctuation never reaches
    the rules (`words`)."""

    if len(label) < 3:
        return False
    if label.isupper() and len(label) <= 4:
        return False
    return not (" " not in label and label.lower() in stop)


def concept_labels(concept: Any) -> list[str]:
    """A concept's labels: preferred (every language), alternative, hidden."""

    labels = [concept.pref_label]
    labels += [str(p.get("label") or "") for p in (concept.extra or {}).get("pref_labels") or []]
    labels += [str(a) for a in concept.alt_labels or []]
    labels += [str(h) for h in concept.hidden_labels or []]
    return labels


# A word as the query's standard tokenizer sees it: letters and digits (with inner
# apostrophes, "Qur'an"), split at spaces and punctuation ("Bhagavad-Gita", "St. Paul"); each
# Han ideograph and hiragana character is a word of its own. The rules are read with
# whitespace splitting, so labels are written in that form.
_WORD = re.compile(r"\w+(?:['\u2019]\w+)*")
_IDEOGRAPH = re.compile(r"([\u3040-\u309f\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff])")


def words(label: str) -> str:
    """A label as space-separated words, the way a query's words arrive at the synonyms."""

    return " ".join(_WORD.findall(_IDEOGRAPH.sub(r" \1 ", label.replace("|", " "))))


def label_forms(labels: Iterable[str], stop: set[str]) -> list[list[str]]:
    """Each usable label's forms (as written, and accent-folded when that differs), labels
    that are the same words once lowercased merged."""

    groups: dict[str, list[str]] = {}
    seen: set[str] = set()
    for raw in labels:
        label = " ".join(str(raw).split())
        if not usable(label, stop):
            continue
        written = words(label)
        if not written:
            continue
        forms: list[str] = []
        for form in (written, fold(written)):
            if form.lower() not in seen:
                seen.add(form.lower())
                forms.append(form)
        if not forms:
            continue
        groups.setdefault(written.lower(), []).extend(forms)
    return list(groups.values())


def synonym_lines(labels: Iterable[str], stop: set[str], weight: float = 1.0) -> list[str]:
    """The synonym rules for one concept's labels.

    At weight 1 the labels are equivalent: one line `a, b, c`, and a query for any of them
    matches all of them alike (name variants: "Odysseus, Ulysses"). Below 1, each label
    keeps its own weight and brings in the others at `weight` (thesaurus terms: "flood"
    also finds "deluge", but texts saying "flood" rank first): `flood => flood, deluge|0.5`.
    """

    groups = label_forms(labels, stop)
    if sum(len(g) for g in groups) < 2:
        return []
    if weight >= 1.0:
        return [", ".join(sorted((f for g in groups for f in g), key=str.lower))]
    w = f"{weight:g}"
    lines: list[str] = []
    for i, group in enumerate(groups):
        others = [
            " ".join(f"{t}|{w}" for t in f.split())
            for j, g in enumerate(groups)
            if j != i
            for f in g
        ]
        for form in group:
            lines.append(f"{form} => " + ", ".join([*group, *others]))
    return lines


def synonyms_text(stop: set[str] | None = None) -> tuple[str, int]:
    """The synonyms file for the active packs, and its number of lines.

    A one-word label that is a stop word of English or of the label's own language is not
    expanded (`stop`, when given, replaces those lists)."""

    from oss_server.knowledge.models import Concept, Pack

    by_language: dict[str, set[str]] = {}

    def stop_for(lang: str) -> set[str]:
        if stop is not None:
            return stop
        code = (lang or "").split("-")[0].lower()
        if code not in by_language:
            by_language[code] = stopwords({"en", code})
        return by_language[code]

    lines: list[str] = []
    seen: set[str] = set()
    concepts = (
        Concept.objects.filter(
            pack__status=Pack.Status.ACTIVE,
            taggable=True,
            kind__in=[Concept.Kind.CONCEPT, Concept.Kind.INDIVIDUAL],
        )
        .order_by("pack__pack_id", "iri")
        .iterator()
    )
    size = len(HEADER.encode())
    dropped = 0
    for concept in concepts:
        weight = 1.0 if concept.kind == Concept.Kind.INDIVIDUAL else CONCEPT_WEIGHT
        lines_ = synonym_lines(concept_labels(concept), stop_for(concept.lang), weight)
        rules = [r for r in lines_ if r not in seen]
        cost = sum(len(r.encode()) + 1 for r in rules)
        if size + cost > MAX_BYTES:
            dropped += 1
            continue
        seen.update(rules)
        lines.extend(rules)
        size += cost
    if dropped:
        log.warning("synonyms: %d concepts left out, over %d bytes", dropped, MAX_BYTES)
    return HEADER + "".join(line + "\n" for line in lines), len(lines)


def sync_synonyms(client: Any = None) -> int:
    """Write the active packs' synonyms into the documents configset and reload the
    collection. Returns the number of synonym lines. Never raises: a failure is logged
    and searching goes on with the previous synonyms."""

    from oss_server.api.search import clear_facet_caches
    from oss_server.services import configset_dir, solr_client, solr_documents_collection

    clear_facet_caches()
    try:
        text, count = synonyms_text()
        client = client or solr_client()
        with tempfile.TemporaryDirectory(prefix="semascope-conf-") as tmp:
            conf = Path(tmp) / "conf"
            shutil.copytree(configset_dir("documents"), conf)
            (conf / SYNONYMS_FILE).write_text(text, encoding="utf-8")
            client.upload_configset("semascope-documents", conf)
        collection = solr_documents_collection()
        if collection in client.list_collections():
            client.reload_collection(collection)
        log.info("synonyms: %d lines from the active packs", count)
        return count
    except Exception:  # noqa: BLE001 - search keeps working with the previous synonyms
        log.exception("synonyms: could not update the documents configset")
        return 0
